interface Config {
  text: string;
  scene: string;
  speed: number;
  tilt: number;
  color: string;
  fontSize: number;
  canvasWidth: number;
  canvasHeight: number;
  output: string;
  noPreview: boolean;
}

// 默认配置
const DEFAULT_CONFIG: Partial<Config> = {
  scene: '江南老宅青瓦屋檐，斑驳墙壁',
  speed: 2.5,
  tilt: 10,
  color: '#d4c5a9',
  fontSize: 24,
  canvasWidth: 1080,
  canvasHeight: 1920,
  output: './text-rain-output',
  noPreview: false,
};

/**
 * 解析命令行参数
 */
function parseArgs(): Config {
  const args = process.argv.slice(2);
  const config = { ...DEFAULT_CONFIG } as Config;

  // 第一个非flag参数作为诗句文本
  const textIndex = args.findIndex(arg => !arg.startsWith('--'));
  if (textIndex !== -1) {
    config.text = args[textIndex];
  }

  // 解析其他参数
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (!arg.startsWith('--')) continue;

    const key = arg.slice(2);
    const value = args[i + 1];

    switch (key) {
      case 'scene':
        config.scene = value;
        i++;
        break;
      case 'speed':
        config.speed = parseFloat(value);
        i++;
        break;
      case 'tilt':
        config.tilt = parseFloat(value);
        i++;
        break;
      case 'color':
        config.color = value;
        i++;
        break;
      case 'font-size':
        config.fontSize = parseInt(value);
        i++;
        break;
      case 'canvas-width':
        config.canvasWidth = parseInt(value);
        i++;
        break;
      case 'canvas-height':
        config.canvasHeight = parseInt(value);
        i++;
        break;
      case 'output':
        config.output = value;
        i++;
        break;
      case 'no-preview':
        config.noPreview = true;
        break;
    }
  }

  if (!config.text) {
    console.error('❌ 错误: 必须提供诗句文本');
    console.log('\n用法示例:');
    console.log('  node generate.ts "床前明月光，疑是地上霜"');
    console.log('  node generate.ts "山重水复疑无路" --scene "苏州园林" --speed 3');
    process.exit(1);
  }

  return config;
}

