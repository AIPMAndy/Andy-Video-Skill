// 质量预设
const QUALITY_PRESETS = {
  low: { resolution: '480p', fps: 15, flag: '-ql' },
  medium: { resolution: '720p', fps: 30, flag: '-qm' },
  high: { resolution: '1080p', fps: 60, flag: '-qh' },
  production: { resolution: '2160p', fps: 60, flag: '-qk' }
};

/**
 * 生成 Manim 动画脚本
 */
async function generateScript(options) {
  const spinner = ora('正在生成 Manim 动画脚本...').start();

  try {
    const { topic, duration, style, outputDir } = options;
    const colorScheme = COLOR_SCHEMES[style] || COLOR_SCHEMES['3blue1brown'];

    // 创建输出目录
    await fs.mkdir(outputDir, { recursive: true });

    // 生成脚本文件名
    const scriptName = topic.toLowerCase().replace(/\s+/g, '_');
    const scriptPath = path.join(outputDir, `${scriptName}_animation.py`);

    // 生成 Python 脚本
    const scriptContent = generatePythonScript(topic, duration, colorScheme);
    await fs.writeFile(scriptPath, scriptContent);

    // 生成渲染脚本
    const renderScriptPath = path.join(outputDir, 'render_all.sh');
    const renderScript = generateRenderScript(scriptName, 'high');
    await fs.writeFile(renderScriptPath, renderScript);
    await fs.chmod(renderScriptPath, 0o755);

    // 生成 README
    const readmePath = path.join(outputDir, 'README.md');
    const readme = generateReadme(topic, scriptName);
    await fs.writeFile(readmePath, readme);

    spinner.succeed(chalk.green('✅ Manim 脚本生成成功！'));

    console.log(chalk.cyan('\n📁 生成的文件:'));
    console.log(chalk.gray(`  - ${scriptPath}`));
    console.log(chalk.gray(`  - ${renderScriptPath}`));
    console.log(chalk.gray(`  - ${readmePath}`));

    return { scriptPath, renderScriptPath, readmePath };
  } catch (error) {
    spinner.fail(chalk.red('❌ 脚本生成失败'));
    throw error;
  }
}

/**
 * 生成 Python Manim 脚本内容
 */
function generatePythonScript(topic, duration, colorScheme) {
  const className = topic.replace(/\s+/g, '');

  return `from manim import *

# ========================================
# ${topic} - Manim Animation
# Generated by andy-manim-video v1.0.0
# ========================================

# 配色方案 (3Blue1Brown 风格)
QUERY_COLOR = "${colorScheme.primary}"      # 青色
KEY_COLOR = "${colorScheme.secondary}"        # 洋红
VALUE_COLOR = "${colorScheme.accent}"       # 黄色
BG_COLOR = "${colorScheme.bg}"         # 深色背景

config.background_color = BG_COLOR


class ${className}Intro(Scene):
    """开场钩子 - 疑问式标题"""

    def construct(self):
        # 配音脚本: "But what is ${topic}? Let's explore this fascinating concept."

        # 标题组件
        title_part1 = Text("But what is", font_size=48)
        keyword = Text("${topic}", font_size=64, color=VALUE_COLOR)
        title_part2 = Text("?", font_size=48)

        title = VGroup(title_part1, keyword, title_part2).arrange(RIGHT, buff=0.3)
        title.move_to(ORIGIN)

        # 动画
        self.play(FadeIn(title_part1), FadeIn(title_part2))
        self.wait(0.5)
        self.play(Write(keyword))
        self.wait(1)

        # 副标题
        subtitle = Text(
            "Let's explore this concept visually",
            font_size=28,
            color=GRAY
        ).next_to(title, DOWN, buff=0.8)

        self.play(FadeIn(subtitle))
        self.wait(2)

        # 清屏
        self.play(*[FadeOut(mob) for mob in self.mobjects])


class ${className}Problem(Scene):
    """问题设定 - 为什么需要这个概念"""

    def construct(self):
        # 配音脚本: "The problem we're trying to solve is..."

        # 问题标题
        problem_title = Text("The Problem:", font_size=44, color=KEY_COLOR)
        problem_title.to_edge(UP, buff=1)

        self.play(Write(problem_title))
        self.wait(1)

        # 问题描述 (这里需要根据具体主题填充)
        problem_desc = Text(
            "Understanding complex concepts requires\\nvisual and intuitive explanations",
            font_size=32
        ).next_to(problem_title, DOWN, buff=1)

        self.play(FadeIn(problem_desc))
        self.wait(2)

        # 清屏
        self.play(
            FadeOut(problem_title),
            FadeOut(problem_desc)
        )


class ${className}Concept(Scene):
    """核心概念讲解"""

    def construct(self):
        # 配音脚本: "The key ingredients are..."

        # 标题
        title = Text("Core Concepts", font_size=48)
        title.to_edge(UP, buff=0.8)
        self.play(Write(title))
        self.wait(1)

        # 三个核心要素 (示例，根据主题调整)
        concept1 = Text("1. Visual Representation", font_size=32, color=QUERY_COLOR)
        concept2 = Text("2. Step-by-Step Breakdown", font_size=32, color=KEY_COLOR)
        concept3 = Text("3. Intuitive Understanding", font_size=32, color=VALUE_COLOR)

        concepts = VGroup(concept1, concept2, concept3).arrange(DOWN, buff=0.6, aligned_edge=LEFT)
        concepts.next_to(title, DOWN, buff=1)

        # 依次显示
        for concept in concepts:
            self.play(FadeIn(concept))
            self.wait(1.5)

        self.wait(2)
        self.play(*[FadeOut(mob) for mob in self.mobjects])


class ${className}Conclusion(Scene):
    """总结与结尾"""

    def construct(self):
        # 配音脚本: "So why does this matter? Here are three key takeaways..."

        # 标题
        title = Text("Why This Matters", font_size=44)
        title.to_edge(UP, buff=1)
        self.play(Write(title))
        self.wait(1)

        # 三大要点
        point1 = Text("→ Simplifies complex ideas", font_size=28)
        point2 = Text("→ Makes learning more engaging", font_size=28)
        point3 = Text("→ Builds intuitive understanding", font_size=28)

        points = VGroup(point1, point2, point3).arrange(DOWN, buff=0.5, aligned_edge=LEFT)
        points.next_to(title, DOWN, buff=1.2)

        for point in points:
            self.play(FadeIn(point))
            self.wait(1.2)

        self.wait(2)
        self.play(FadeOut(VGroup(*self.mobjects)))

        # 结尾名言
        quote = Text(
            "Visual thinking is powerful",
            font_size=48,
            color=VALUE_COLOR
        )

        self.play(Write(quote))
        self.wait(3)
        self.play(FadeOut(quote))


# ========================================
# 使用说明
# ========================================
# 渲染单个场景（预览）:
#   manim -pql ${topic.toLowerCase().replace(/\s+/g, '_')}_animation.py ${className}Intro
#
# 渲染所有场景（高质量）:
#   ./render_all.sh high
#
# 场景列表:
#   - ${className}Intro: 开场钩子
#   - ${className}Problem: 问题设定
#   - ${className}Concept: 核心概念
#   - ${className}Conclusion: 总结结尾
`;
}

/**
 * 生成渲染脚本
 */
function generateRenderScript(scriptName, defaultQuality) {
  return `#!/bin/bash
# Manim 批量渲染脚本
# Generated by andy-manim-video

set -e

SCRIPT_NAME="${scriptName}_animation.py"
QUALITY=\${1:-${defaultQuality}}

# 质量参数映射
case "\$QUALITY" in
  low)
    QUALITY_FLAG="-ql"
    RES="480p15"
    ;;
  medium)
    QUALITY_FLAG="-qm"
    RES="720p30"
    ;;
  high)
    QUALITY_FLAG="-qh"
    RES="1080p60"
    ;;
  production)
    QUALITY_FLAG="-qk"
    RES="2160p60"
    ;;
  *)
    echo "❌ Unknown quality: \$QUALITY"
    echo "Usage: ./render_all.sh [low|medium|high|production]"
    exit 1
    ;;
esac

echo "🎬 Rendering all scenes at \$QUALITY quality (\$RES)"
echo ""

# 提取所有场景类名
SCENES=$(grep "^class.*Scene" "\$SCRIPT_NAME" | sed 's/class \\(.*\\)(Scene):.*/\\1/')

# 渲染每个场景
for scene in \$SCENES; do
  echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
  echo "🎥 Rendering: \$scene"
  echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

  manim -p \$QUALITY_FLAG "\$SCRIPT_NAME" "\$scene"

  if [ $? -eq 0 ]; then
    echo "✅ \$scene completed"
  else
    echo "❌ \$scene failed"
    exit 1
  fi
  echo ""
done

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🎉 All scenes rendered successfully!"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
`;
}

