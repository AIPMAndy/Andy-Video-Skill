/**
 * 渲染视频
 */
async function renderVideo(options) {
  const { scriptPath, quality, scenes } = options;
  const qualityPreset = QUALITY_PRESETS[quality];

  const spinner = ora(`正在渲染视频 (${qualityPreset.resolution}@${qualityPreset.fps}fps)...`).start();

  try {
    const scriptDir = path.dirname(scriptPath);
    const scriptFile = path.basename(scriptPath);

    if (scenes && scenes.length > 0) {
      // 渲染指定场景
      for (const scene of scenes) {
        spinner.text = `渲染场景: ${scene}`;
        const cmd = `cd "${scriptDir}" && manim -p ${qualityPreset.flag} "${scriptFile}" ${scene}`;
        await execAsync(cmd);
      }
    } else {
      // 渲染所有场景（使用 render_all.sh）
      const renderScript = path.join(scriptDir, 'render_all.sh');
      const cmd = `cd "${scriptDir}" && bash render_all.sh ${quality}`;
      await execAsync(cmd);
    }

    spinner.succeed(chalk.green('✅ 视频渲染完成！'));

    // 列出生成的视频文件
    const outputDir = path.join(scriptDir, 'media', 'videos');
    console.log(chalk.cyan('\n📹 生成的视频文件:'));
    console.log(chalk.gray(`  ${outputDir}`));

  } catch (error) {
    spinner.fail(chalk.red('❌ 视频渲染失败'));
    console.error(chalk.red(error.message));
    throw error;
  }
}

/**
 * 完整工作流
 */
async function fullWorkflow(options) {
  console.log(chalk.bold.cyan('\n🎬 Andy Manim Video - 完整工作流\n'));

  // Step 1: 生成脚本
  console.log(chalk.yellow('📝 Step 1: 生成 Manim 脚本'));
  const { scriptPath } = await generateScript(options);

  // Step 2: 询问是否立即渲染
  const { shouldRender } = await inquirer.prompt([
    {
      type: 'confirm',
      name: 'shouldRender',
      message: '是否立即渲染视频？',
      default: true
    }
  ]);

  if (shouldRender) {
    // Step 3: 选择质量
    const { quality } = await inquirer.prompt([
      {
        type: 'list',
        name: 'quality',
        message: '选择渲染质量:',
        choices: [
          { name: '🔸 Low (480p15) - 快速预览', value: 'low' },
          { name: '🔹 Medium (720p30) - 测试', value: 'medium' },
          { name: '🔷 High (1080p60) - 发布版本 (推荐)', value: 'high' },
          { name: '💎 Production (4K60) - 专业级', value: 'production' }
        ],
        default: 'high'
      }
    ]);

    console.log(chalk.yellow('\n🎥 Step 2: 渲染视频'));
    await renderVideo({ scriptPath, quality });
  }

  console.log(chalk.bold.green('\n✨ 工作流完成！\n'));
  console.log(chalk.cyan('📋 下一步建议:'));
  console.log(chalk.gray('  1. 检查视频质量'));
  console.log(chalk.gray('  2. 录制配音'));
  console.log(chalk.gray('  3. 添加背景音乐'));
  console.log(chalk.gray('  4. 视频合成（DaVinci Resolve/iMovie）'));
  console.log(chalk.gray('  5. 设计缩略图'));
  console.log(chalk.gray('  6. 发布到 YouTube\n'));
}

