program
  .name('andy-manim-video')
  .description('3Blue1Brown 风格的 Manim 程序化动画视频制作系统')
  .version('1.0.0');

program
  .command('generate')
  .description('生成 Manim 动画脚本')
  .option('-t, --topic <topic>', '视频主题', 'Attention Mechanism')
  .option('-d, --duration <minutes>', '视频时长（分钟）', '2')
  .option('-s, --style <style>', '视觉风格', '3blue1brown')
  .option('-o, --output-dir <dir>', '输出目录', process.cwd())
  .action(async (options) => {
    try {
      await generateScript(options);
    } catch (error) {
      console.error(chalk.red('错误:'), error.message);
      process.exit(1);
    }
  });

program
  .command('render')
  .description('渲染 Manim 视频')
  .option('-s, --script <path>', '脚本路径（必需）')
  .option('-q, --quality <quality>', '渲染质量 (low|medium|high|production)', 'high')
  .option('--scenes <scenes...>', '要渲染的场景（可选）')
  .action(async (options) => {
    try {
      if (!options.script) {
        console.error(chalk.red('错误: 必须指定脚本路径 (-s)'));
        process.exit(1);
      }
      await renderVideo({ scriptPath: options.script, quality: options.quality, scenes: options.scenes });
    } catch (error) {
      console.error(chalk.red('错误:'), error.message);
      process.exit(1);
    }
  });

program
  .command('full')
  .description('完整工作流：生成脚本 + 渲染视频')
  .option('-t, --topic <topic>', '视频主题', 'Attention Mechanism')
  .option('-d, --duration <minutes>', '视频时长（分钟）', '2')
  .option('-s, --style <style>', '视觉风格', '3blue1brown')
  .option('-o, --output-dir <dir>', '输出目录', process.cwd())
  .action(async (options) => {
    try {
      await fullWorkflow(options);
    } catch (error) {
      console.error(chalk.red('错误:'), error.message);
      process.exit(1);
    }
  });

program.parse();
